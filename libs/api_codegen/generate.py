#!/usr/bin/env python3
"""Generate strict JSON DTOs and Drogon bindings from the supported OpenAPI subset.
api.yaml is loaded with a safe YAML loader; unsupported schema constructs fail generation.
"""
import argparse, hashlib, json, re
from pathlib import Path
from route_policy import load, operations as validated_operations

def generate(service):
    source=service/'docs/api.yaml'; raw=source.read_bytes(); spec=load(service)
    namespace=spec['x-cpp-namespace']
    assert re.fullmatch(r'[A-Za-z_:]+',namespace)
    lines=['// Generated by libs/api_codegen/generate.py. DO NOT EDIT.', '// Schema SHA256: '+hashlib.sha256(raw).hexdigest(), '#pragma once', '#include <drogon/drogon.h>', '#include <cstdint>', '#include <regex>', '#include <stdexcept>', '#include <string>', f'namespace {namespace} {{', 'using Callback = std::function<void(const drogon::HttpResponsePtr&)>;', 'using Handler = std::function<void(const drogon::HttpRequestPtr&, Callback&&)>;']
    for name,schema in spec['components']['schemas'].items():
        assert re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*',name)
        assert schema['type']=='object' and set(schema['required'])==set(schema['properties'])
        lines += [f'struct {name} {{']
        for field,prop in schema['properties'].items():
            assert re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*',field)
            assert prop['type'] in ('string','integer')
            lines += [f'    {"std::string" if prop["type"]=="string" else "std::int64_t"} {field}{{}};']
        lines += [f'    static {name} FromJson(const Json::Value& body) {{', '        if (!body.isObject()) throw std::invalid_argument("JSON object required");', f'        {name} result;']
        for field,prop in schema['properties'].items():
            v='body['+json.dumps(field)+']'; isstr=prop['type']=='string'
            lines += [f'        if (!{v}.{"isString" if isstr else "isInt64"}()) throw std::invalid_argument("invalid {field}");', f'        result.{field} = {v}.{"asString" if isstr else "asInt64"}();']
            checks=[]
            if 'pattern' in prop:checks += [f'!std::regex_match(result.{field}, std::regex({json.dumps(prop["pattern"])}))']
            for key,op in [('x-min-bytes','<'),('x-max-bytes','>')]:
                if key in prop:checks += [f'result.{field}.size() {op} {prop[key]}']
            if prop.get('x-no-nul'):checks += [f"result.{field}.find('\\0') != std::string::npos"]
            if 'minimum' in prop:checks += [f'result.{field} < {prop["minimum"]}']
            if 'enum' in prop:checks += ['('+' && '.join(f'result.{field} != {json.dumps(x)}' for x in prop['enum'])+')']
            if checks:lines += [f'        if ({" || ".join(checks)}) throw std::invalid_argument("invalid {field}");']
        lines += ['        return result;', '    }', '    Json::Value ToJson() const {', '        Json::Value result(Json::objectValue);']
        for field,prop in schema['properties'].items():
            value=field if prop['type']=='string' else f'Json::Int64({field})'
            lines += [f'        result["{field}"] = {value};']
        lines += ['        return result;', '    }', '};']
    operations=[]
    policies={}
    for path,method,operation in validated_operations(spec):
        operations.append((path,method,operation['operationId']))
        for alias in operation.get('x-backend-aliases', []):
            operations.append((alias,method,operation['operationId']))
        policies[operation['operationId']]=operation['x-route']
    assert len({(path, method) for path,method,_ in operations})==len(operations)
    lines += ['struct Handlers {']+[f'    Handler {op};' for op in dict.fromkeys(op for _,_,op in operations)]+['};','inline void RegisterRoutes(const Handlers& handlers) {']
    lines += [f'    drogon::app().setClientMaxBodySize({max(p["max_body_bytes"] for p in policies.values())});']
    for path,method,op in operations:
        lines += [f'    if (!handlers.{op}) throw std::invalid_argument("missing handler: {op}");',
            f'    drogon::app().registerHandler({json.dumps(path)}, [handler=handlers.{op}](const drogon::HttpRequestPtr& request, Callback&& done) {{',
            f'        if (request->body().size() > {policies[op]["max_body_bytes"]}) {{',
            '            auto response = drogon::HttpResponse::newHttpResponse();',
            '            response->setStatusCode(static_cast<drogon::HttpStatusCode>(413));',
            '            done(response); return;', '        }',
            '        handler(request, std::move(done));', f'    }}, {{drogon::{method.capitalize()}}});']
    lines += ['}', '}']
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('services',nargs='+',type=Path);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    for service in args.services:
        text=generate(service);path=service/'src/generated/api.hpp'
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit(f'Stale generated API: {path}')
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
