#!/usr/bin/env python3
"""Generate a small typed public Dart client from the validated OpenAPI subset."""
import argparse
import json
from pathlib import Path
from route_policy import load, operations, require

ROOT = Path(__file__).resolve().parents[2]


def camel(value):
    first, *rest = value.split('_')
    return first + ''.join(s.title() for s in rest)


def render(service):
    spec = load(service)
    lines = ['// Generated by libs/api_codegen/generate_dart.py. DO NOT EDIT.',
             "import '../transport.dart';", '']
    types = {'string': 'String', 'integer': 'int'}
    for name, schema in spec['components']['schemas'].items():
        name = 'Api' + name
        require(schema['type'] == 'object' and set(schema['required']) == set(schema['properties']), 'Only required object fields are supported')
        fields = schema['properties']
        lines += [f'class {name} {{', f'  const {name}({{{", ".join("required this." + camel(f) for f in fields)}}});']
        for field, prop in fields.items():
            require(prop['type'] in types, 'Unsupported Dart field type')
            lines += [f'  final {types[prop["type"]]} {camel(field)};']
        lines += [f'  factory {name}.fromJson(Map<String, dynamic> json) => {name}(']
        for field, prop in fields.items():
            lines += [f"    {camel(field)}: json['{field}'] as {types[prop['type']]},"]
        lines += ['  );', '  Map<String, dynamic> toJson() => {']
        lines += [f"    '{field}': {camel(field)}," for field in fields]
        lines += ['  };', '}', '']
    lines += [f'class {service.name.title()}Api {{', f'  const {service.name.title()}Api(this.transport);', '  final ApiTransport transport;']
    for path, method, op in operations(spec):
        if op['x-route']['exposure'] != 'public':
            continue
        args = []
        body = op.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema')
        if body:
            require(set(body) == {'$ref'}, 'Only referenced request DTOs are supported')
            args += ['Api' + body['$ref'].split('/')[-1] + ' body']
        auth = op['x-route']['auth'] != 'none'
        if auth: args += ['String accessToken']
        success = [(int(status), response) for status, response in op['responses'].items() if status.startswith('2')]
        require(len(success) == 1, 'Exactly one successful response is required')
        status, response = success[0]
        schema = response.get('content', {}).get('application/json', {}).get('schema')
        result = 'void'
        if schema:
            require(set(schema) == {'$ref'}, 'Only referenced response DTOs are supported')
            result = 'Api' + schema['$ref'].split('/')[-1]
        lines += [f'  Future<{result}> {camel(op["operationId"])}({", ".join(args)}) async {{']
        prefix = 'final data = ' if schema else ''
        lines += [f"    {prefix}await transport.request('{method.upper()}', '{path}',", f'      expectedStatus: {status},', f"      timeout: const Duration(seconds: {op['x-route']['timeouts']['read_seconds']}),"]
        if body: lines += ['      body: body.toJson(),']
        if auth: lines += ['      accessToken: accessToken,']
        lines += ['    );']
        if schema: lines += [f'    return {result}.fromJson(data);']
        lines += ['  }']
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); args = p.parse_args()
    for service in ('auth', 'whoami'):
        output = ROOT / f'services/web/lib/api/generated/{service}_api.dart'
        content = render(ROOT / 'services' / service)
        if args.check:
            require(output.exists() and output.read_text() == content, f'Stale Dart client: {output}')
        else:
            output.parent.mkdir(parents=True, exist_ok=True); output.write_text(content)


if __name__ == '__main__': main()
